#!/usr/bin/env bun
import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";

import {
  repoRoot,
  repoUserJs,
  repoOverrides,
  lockPath,
  cacheDir,
} from "./lib/paths.mjs";
import { atomicWrite, ensureDir, exists, sha256 } from "./lib/fsx.mjs";
import { bold, dim, step, info, ok, warn, fail } from "./lib/log.mjs";

const USAGE = `
hanok update — regenerate user.js from the pinned arkenfox base

Usage:
  bun scripts/update-arkenfox.mjs [options]

Options:
  --check     report whether user.js is current (exit 1 if not)
  --offline   use the cached arkenfox copy only
  -h, --help  show this help
`;

const { values: args } = parseArgs({
  options: {
    check: { type: "boolean", default: false },
    offline: { type: "boolean", default: false },
    help: { type: "boolean", short: "h", default: false },
  },
  allowPositionals: false,
});

if (args.help) {
  console.log(USAGE.trim());
  process.exit(0);
}

function header(lock) {
  return `/***
 * hanok — generated user.js
 * base: arkenfox v${lock.version} (${lock.tag}) @ ${lock.commit.slice(0, 12)}
 * overrides: user-overrides.js
 *
 * Do not edit this file. Edit user-overrides.js and run: mise run update
 ***/`;
}

function render(lock, base, overrides) {
  return `${header(lock)}

${base.trimEnd()}

// ===== hanok overrides =====
${overrides.trimEnd()}
`;
}

async function loadBase(lock) {
  await ensureDir(cacheDir);
  const cachePath = path.join(cacheDir, `arkenfox-${lock.commit}.js`);

  if (exists(cachePath)) {
    const cached = await fsp.readFile(cachePath, "utf8");
    if (sha256(cached) === lock.sha256) {
      ok(`using cached arkenfox ${lock.version}`);
      return cached;
    }
    warn("cached arkenfox checksum mismatch; refetching");
  }

  if (args.offline) {
    throw new Error("no valid cached arkenfox copy; rerun without --offline");
  }

  const response = await fetch(lock.url, { redirect: "follow" });
  if (!response.ok) {
    throw new Error(`arkenfox download failed: HTTP ${response.status}`);
  }
  const body = await response.text();
  const digest = sha256(body);
  if (digest !== lock.sha256) {
    throw new Error(
      `arkenfox checksum mismatch\n  expected ${lock.sha256}\n  actual   ${digest}`,
    );
  }

  await atomicWrite(cachePath, body);
  ok(`downloaded arkenfox ${lock.version}`);
  return body;
}

async function main() {
  step(bold("hanok update"));
  info(dim(`repo: ${repoRoot}`));

  const lock = JSON.parse(await fsp.readFile(lockPath, "utf8"));
  const overrides = await fsp.readFile(repoOverrides, "utf8");
  const base = await loadBase(lock);
  const output = render(lock, base, overrides);

  const current = exists(repoUserJs) ? await fsp.readFile(repoUserJs, "utf8") : "";
  if (current === output) {
    ok("user.js already current");
    return;
  }

  if (args.check) {
    warn("user.js differs from the pinned base + overrides");
    process.exit(1);
  }

  await atomicWrite(repoUserJs, output);
  ok(`wrote ${repoUserJs}`);
  info("next: mise run apply");
}

try {
  await main();
} catch (error) {
  fail(error.message);
  process.exit(1);
}
